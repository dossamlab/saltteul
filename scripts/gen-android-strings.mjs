// Writes android/app/src/main/res/values/saltteul_strings.xml from copy/ko.json.
// Keys starting with "widget." plus app.name, weekday.*, owner.*, date.* become Android strings.
// Name mapping: "widget.todayTitle" -> "widget_todayTitle". Placeholders {a} {b} -> %1$s %2$s in the order listed in the spec.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const ko = JSON.parse(readFileSync('copy/ko.json', 'utf8'))
const spec = JSON.parse(readFileSync('copy/copy-spec.json', 'utf8'))
const varsByKey = Object.fromEntries(spec.entries.map((e) => [e.key, e.vars ?? []]))
// app.name is already provided as @string/app_name by the Capacitor template.
const wanted = (k) => k.startsWith('widget.') || k.startsWith('weekday.') || k.startsWith('owner.') || k.startsWith('date.')

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/'/g, "\\'").replace(/"/g, '\\"').replace(/@/g, '\\@').replace(/\?/g, '\\?')

const lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by scripts/gen-android-strings.mjs from copy/ko.json. Do not edit. -->', '<resources>']
for (const [key, value] of Object.entries(ko).sort()) {
  if (!wanted(key)) continue
  const vars = varsByKey[key] ?? [...value.matchAll(/\{(\w+)\}/g)].map((m) => m[1])
  let v = esc(value)
  vars.forEach((name, i) => { v = v.replaceAll(`{${name}}`, `%${i + 1}$s`) })
  const formatted = vars.length ? '' : ' formatted="false"'
  lines.push(`  <string name="${key.replace(/\./g, '_')}"${formatted}>${v}</string>`)
}
lines.push('</resources>', '')
const out = 'android/app/src/main/res/values/saltteul_strings.xml'
if (!existsSync('android/app/src/main/res/values')) throw new Error('android project missing')
writeFileSync(out, lines.join('\n'))
console.log('wrote', out)
